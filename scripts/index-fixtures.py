#!/usr/bin/env python3
"""Write real docs-bootstrap backlog indexes into core's common tests (B-06).

    python3 scripts/index-fixtures.py youndie/appframe@<sha> youndie/kachok@<sha> ...

Each `backlog.md` is fetched with `gh api` at the commit named and written as a Kotlin raw string,
so the same text is parsed on desktop and on wasmJs, where a test cannot read a file. The commit is
written beside each text: a fixture is evidence of the format on that day, and the next refresh is a
new commit, not an edit.
"""
import base64
import json
import pathlib
import subprocess
import sys

OUT = pathlib.Path("core/src/commonTest/kotlin/io/github/youndie/pyatiletka/core/RealIndexes.kt")


def fetch(repo, sha):
    out = subprocess.run(["gh", "api", f"repos/{repo}/contents/backlog.md?ref={sha}"], check=True, capture_output=True, text=True).stdout
    return base64.b64decode(json.loads(out)["content"]).decode("utf-8")


def kotlin_raw(text):
    if '"""' in text:
        sys.exit("a triple quote in the text; extend the escaping")
    return text.replace("$", "${'$'}")


def main(args):
    parts = ["package io.github.youndie.pyatiletka.core", "", "// Generated by scripts/index-fixtures.py — real backlog.md files at the commits named. Do not edit.", ""]
    for arg in args:
        repo, sha = arg.split("@")
        name = "".join(p.capitalize() for p in repo.split("/")[1].split("-"))
        parts += [f"/** `{repo}` at `{sha}`. */", f'val {name[0].lower() + name[1:]}Index: String =', '    """' + kotlin_raw(fetch(repo, sha)) + '"""', ""]
    OUT.write_text("\n".join(parts))
    print("wrote", OUT)


if __name__ == "__main__":
    main(sys.argv[1:])
